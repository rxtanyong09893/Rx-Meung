alter table public.facilities   enable row level security;
alter table public.profiles     enable row level security;
alter table public.drugs        enable row level security;
alter table public.stock_levels enable row level security;
alter table public.lots         enable row level security;
alter table public.stock_tx     enable row level security;

create policy fac_read   on public.facilities for select to authenticated using (true);
create policy fac_admin  on public.facilities for all    to authenticated using (public.is_admin()) with check (public.is_admin());

create policy prof_read  on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy prof_admin on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy drug_read  on public.drugs for select to authenticated using (true);
create policy drug_admin on public.drugs for all    to authenticated using (public.is_admin()) with check (public.is_admin());

create policy lvl_read   on public.stock_levels for select to authenticated using (public.can_access(facility_id));
create policy lvl_write  on public.stock_levels for all    to authenticated using (public.can_access(facility_id)) with check (public.can_access(facility_id));

-- lots / stock_tx: อ่านได้ตามสิทธิ์ แต่เขียนได้ผ่านฟังก์ชันด้านล่างเท่านั้น
create policy lot_read   on public.lots     for select to authenticated using (public.can_access(facility_id));
create policy tx_read    on public.stock_tx for select to authenticated using (public.can_access(facility_id));

-- ---------- ฟังก์ชันทำรายการคลัง ----------
create or replace function public._balance(p_fac integer, p_drug integer) returns numeric
language sql stable set search_path = public as $$
  select coalesce(sum(qty), 0) from lots where facility_id = p_fac and drug_id = p_drug;
$$;

-- รับยาเข้าคลัง (หรือบันทึกยอดยกมา เมื่อ p_opening = true)
create or replace function public.receive_stock(
  p_facility_id integer, p_drug_id integer, p_qty numeric,
  p_lot_no text, p_exp_date date, p_unit_cost numeric default null,
  p_tx_date date default null, p_ref_no text default null,
  p_source text default null, p_note text default null, p_opening boolean default false
) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_lot bigint; v_tx bigint;
begin
  if not can_access(p_facility_id) then raise exception 'ไม่มีสิทธิ์ทำรายการของหน่วยบริการนี้'; end if;
  if p_qty is null or p_qty <= 0 then raise exception 'จำนวนต้องมากกว่า 0'; end if;
  if p_exp_date is null then raise exception 'กรุณาระบุวันหมดอายุ'; end if;
  perform pg_advisory_xact_lock(p_facility_id, p_drug_id);

  insert into lots (facility_id, drug_id, lot_no, exp_date, qty, unit_cost)
  values (p_facility_id, p_drug_id, coalesce(nullif(trim(p_lot_no), ''), '-'), p_exp_date, p_qty, p_unit_cost)
  on conflict (facility_id, drug_id, lot_no, exp_date)
  do update set qty = lots.qty + excluded.qty,
                unit_cost = coalesce(excluded.unit_cost, lots.unit_cost)
  returning id into v_lot;

  insert into stock_tx (facility_id, drug_id, lot_id, tx_type, qty, balance_after, tx_date, ref_no, source, note)
  values (p_facility_id, p_drug_id, v_lot,
          case when p_opening then 'opening' else 'receive' end,
          p_qty, _balance(p_facility_id, p_drug_id), coalesce(p_tx_date, current_date),
          p_ref_no, p_source, p_note)
  returning id into v_tx;
  return v_tx;
end $$;

-- จ่ายยาแบบ FEFO (ล็อตหมดอายุก่อนจ่ายก่อน) ไม่จ่ายล็อตที่หมดอายุแล้ว
create or replace function public.dispense_stock(
  p_facility_id integer, p_drug_id integer, p_qty numeric,
  p_tx_date date default null, p_ref_no text default null,
  p_source text default null, p_note text default null
) returns numeric
language plpgsql security definer set search_path = public as $$
declare r record; v_left numeric := p_qty; v_take numeric; v_avail numeric;
        v_date date := coalesce(p_tx_date, current_date);
begin
  if not can_access(p_facility_id) then raise exception 'ไม่มีสิทธิ์ทำรายการของหน่วยบริการนี้'; end if;
  if p_qty is null or p_qty <= 0 then raise exception 'จำนวนต้องมากกว่า 0'; end if;
  perform pg_advisory_xact_lock(p_facility_id, p_drug_id);

  select coalesce(sum(qty), 0) into v_avail from lots
   where facility_id = p_facility_id and drug_id = p_drug_id and exp_date >= v_date;
  if v_avail < p_qty then
    raise exception 'ยาที่ยังไม่หมดอายุคงเหลือไม่พอ (คงเหลือ %)', v_avail;
  end if;

  for r in select id, qty from lots
            where facility_id = p_facility_id and drug_id = p_drug_id
              and qty > 0 and exp_date >= v_date
            order by exp_date, id
            for update
  loop
    exit when v_left <= 0;
    v_take := least(r.qty, v_left);
    update lots set qty = qty - v_take where id = r.id;
    v_left := v_left - v_take;
    insert into stock_tx (facility_id, drug_id, lot_id, tx_type, qty, balance_after, tx_date, ref_no, source, note)
    values (p_facility_id, p_drug_id, r.id, 'dispense', -v_take,
            _balance(p_facility_id, p_drug_id), v_date, p_ref_no, p_source, p_note);
  end loop;
  return _balance(p_facility_id, p_drug_id);
end $$;

-- ปรับยอดรายล็อต
--   p_type = 'expire' : p_qty = จำนวนที่ตัดออก (หมดอายุ/เสื่อมสภาพ/แตกหัก)
--   p_type = 'adjust' : p_qty = จำนวนที่ตรวจนับได้จริง (ระบบคำนวณส่วนต่างให้)
create or replace function public.lot_adjust(
  p_lot_id bigint, p_type text, p_qty numeric,
  p_tx_date date default null, p_note text default null
) returns numeric
language plpgsql security definer set search_path = public as $$
declare v_lot lots%rowtype; v_change numeric;
begin
  select * into v_lot from lots where id = p_lot_id;
  if not found then raise exception 'ไม่พบล็อตยา'; end if;
  if not can_access(v_lot.facility_id) then raise exception 'ไม่มีสิทธิ์ทำรายการของหน่วยบริการนี้'; end if;
  if p_qty is null or p_qty < 0 then raise exception 'จำนวนไม่ถูกต้อง'; end if;
  perform pg_advisory_xact_lock(v_lot.facility_id, v_lot.drug_id);
  select * into v_lot from lots where id = p_lot_id for update;

  if p_type = 'expire' then
    if p_qty = 0 or p_qty > v_lot.qty then raise exception 'จำนวนที่ตัดต้องมากกว่า 0 และไม่เกินคงเหลือ (%)', v_lot.qty; end if;
    v_change := -p_qty;
  elsif p_type = 'adjust' then
    if coalesce(trim(p_note), '') = '' then raise exception 'กรุณาระบุเหตุผลการปรับยอด'; end if;
    v_change := p_qty - v_lot.qty;
    if v_change = 0 then return v_lot.qty; end if;
  else
    raise exception 'ประเภทรายการไม่ถูกต้อง';
  end if;

  update lots set qty = qty + v_change where id = p_lot_id;
  insert into stock_tx (facility_id, drug_id, lot_id, tx_type, qty, balance_after, tx_date, note)
  values (v_lot.facility_id, v_lot.drug_id, p_lot_id, p_type, v_change,
          _balance(v_lot.facility_id, v_lot.drug_id), coalesce(p_tx_date, current_date), p_note);
  return v_lot.qty + v_change;
end $$;

revoke execute on function public.receive_stock, public.dispense_stock, public.lot_adjust, public._balance from public, anon;
grant  execute on function public.receive_stock, public.dispense_stock, public.lot_adjust to authenticated;

-- ---------- View สรุปคงคลัง ----------
create or replace view public.v_stock with (security_invoker = true) as
select f.id as facility_id, f.name as facility_name,
       d.id as drug_id, d.code, d.name as drug_name, d.strength, d.unit, d.category, d.unit_price,
       coalesce(l.total_qty, 0)    as total_qty,
       coalesce(l.expired_qty, 0)  as expired_qty,
       coalesce(l.near_exp_qty, 0) as near_exp_qty,     -- หมดอายุภายใน 90 วัน
       l.nearest_exp,
       coalesce(u.used_90d, 0) / 3.0 as avg_monthly_use, -- ใช้เฉลี่ยต่อเดือน (ย้อนหลัง 3 เดือน)
       coalesce(sl.min_qty, 0) as min_qty, sl.max_qty
from public.facilities f
cross join public.drugs d
left join lateral (
  select sum(qty) as total_qty,
         sum(qty) filter (where exp_date < current_date) as expired_qty,
         sum(qty) filter (where exp_date >= current_date and exp_date < current_date + 90) as near_exp_qty,
         min(exp_date) filter (where qty > 0) as nearest_exp
  from public.lots where facility_id = f.id and drug_id = d.id
) l on true
left join lateral (
  select -sum(qty) as used_90d from public.stock_tx
  where facility_id = f.id and drug_id = d.id and tx_type = 'dispense' and tx_date >= current_date - 90
) u on true
left join public.stock_levels sl on sl.facility_id = f.id and sl.drug_id = d.id
where f.active and d.active and public.can_access(f.id);

grant select on public.v_stock to authenticated;

