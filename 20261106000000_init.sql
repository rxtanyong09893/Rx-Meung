-- ---------- ตารางหลัก ----------
create table public.facilities (
  id      integer generated by default as identity primary key,
  hcode   text unique not null,          -- รหัสหน่วยบริการ 5 หลัก
  name    text not null,
  active  boolean not null default true
);

create table public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  email       text,
  full_name   text,
  facility_id integer references public.facilities(id),
  role        text not null default 'staff' check (role in ('admin','staff')),
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

create table public.drugs (
  id           integer generated by default as identity primary key,
  code         text unique,                 -- รหัสยา (ใช้ตอนนำเข้า CSV)
  name         text not null,
  strength     text,
  dosage_form  text,
  unit         text not null default 'เม็ด',
  category     text,                        -- เช่น ED/NED, ยาเรื้อรัง, เวชภัณฑ์
  unit_price   numeric(12,2) not null default 0,
  active       boolean not null default true,
  created_at   timestamptz not null default now()
);

-- จุดสั่งซื้อ (min) / ระดับสูงสุด (max) แยกราย รพ.สต.
create table public.stock_levels (
  facility_id integer not null references public.facilities(id) on delete cascade,
  drug_id     integer not null references public.drugs(id) on delete cascade,
  min_qty     numeric not null default 0,
  max_qty     numeric,
  primary key (facility_id, drug_id)
);

-- ล็อตยาในคลังของแต่ละ รพ.สต.
create table public.lots (
  id          bigint generated by default as identity primary key,
  facility_id integer not null references public.facilities(id),
  drug_id     integer not null references public.drugs(id),
  lot_no      text not null default '-',
  exp_date    date not null,
  qty         numeric not null default 0 check (qty >= 0),
  unit_cost   numeric(12,2),
  created_at  timestamptz not null default now(),
  unique (facility_id, drug_id, lot_no, exp_date)
);
create index lots_fac_drug_exp on public.lots (facility_id, drug_id, exp_date);

-- บัญชีความเคลื่อนไหว (ห้ามแก้ไขย้อนหลัง — บันทึกผ่านฟังก์ชันเท่านั้น)
create table public.stock_tx (
  id            bigint generated by default as identity primary key,
  facility_id   integer not null references public.facilities(id),
  drug_id       integer not null references public.drugs(id),
  lot_id        bigint references public.lots(id),
  tx_type       text not null check (tx_type in ('opening','receive','dispense','adjust','expire')),
  qty           numeric not null,          -- บวก = เข้า, ลบ = ออก
  balance_after numeric not null,          -- คงเหลือรวมของยานั้นหลังทำรายการ
  tx_date       date not null default current_date,
  ref_no        text,                      -- เลขที่ใบเบิก/ใบส่งของ
  source        text,                      -- รับจาก / จ่ายให้
  note          text,
  created_by    uuid default auth.uid() references auth.users(id),
  created_at    timestamptz not null default now()
);
create index stock_tx_fac_date on public.stock_tx (facility_id, tx_date);
create index stock_tx_fac_drug on public.stock_tx (facility_id, drug_id);

-- ---------- ฟังก์ชันสิทธิ์ ----------
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin' and active);
$$;

create or replace function public.my_facility() returns integer
language sql stable security definer set search_path = public as $$
  select facility_id from profiles where id = auth.uid() and active;
$$;

create or replace function public.can_access(fid integer) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or (fid is not null and fid = public.my_facility());
$$;

-- สร้าง profile อัตโนมัติเมื่อมีผู้สมัครใหม่ (admin ต้องกำหนด รพ.สต. ให้ก่อนใช้งาน)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', ''));
  return new;
end $$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

